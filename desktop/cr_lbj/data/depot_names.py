#: 制造厂并列分隔符（号段表里有 `四方/唐山`、`大连|戚墅堰` 两种写法）
_MAKER_SPLIT_RE = re.compile(r'\s*[/|、]\s*')

#: 这些不是配属/制造厂名称，不要硬翻
_PLACEHOLDERS = {'', '----', '---', '—', '暂无数据', '未知', '不详',
                 '配属未知', '未知配属', '暂无局段', '局段未知'}


def _clean(value: Any) -> str:
    return str(value if value is not None else '').strip()


def full_bureau(text: Any) -> str:
    """局简称 → 全称局名；已是全称/未知写法时原样返回。

    `南局` → `南昌局`、`京局` → `北京局`；`南昌局集团公司` 不动
    （RailGo 的 `bureauName` 常以简称返回，车次卡必须展开成全称）。
    """
    s = _clean(text)
    if not s:
        return ''
    m = _BUREAU_RE.match(s)
    if m:
        return _BUREAUS[m.group(1)] + s[2:]
    return s


def full_depot(text: Any) -> str:
    """号段表配属简称 → 全称配属单位（查不到原样返回，绝不猜）。"""
    s = _clean(text)
    if not s or s in _PLACEHOLDERS:
        return s
    # 拆出括号备注，只翻译主名，备注原样保留
    m = _TAIL_RE.match(s)
    base, tail = (m.group(1).strip(), m.group(2)) if m else (s, '')
    hit = _DEPOTS.get(base)
    if hit:
        return hit + tail
    bm = _BUREAU_RE.match(base)
    if bm:
        # 只写了局（如 `哈局`）：补全成 `哈尔滨局`
        rest = base[2:]                    # 去掉「X局」两个字
        if not rest:
            return _BUREAUS[bm.group(1)] + tail
        # 形如 `沈局锦州车辆段`：局名是简称、段名本身已是完整地名 → 只换局名。
        # 2 字及以下（`南段`/`沪段`）仍属配属简称，没收录就原样返回，不拼半截。
        if len(rest) > 2 and (rest.endswith('段') or rest.endswith('所')):
            return _BUREAUS[bm.group(1)] + rest + tail
    return s


def full_maker(text: Any) -> str:
    """制造厂短名 → 公司全称；多厂并列逐个翻译，未知写法原样返回。"""
    s = _clean(text)
    if not s or s in _PLACEHOLDERS:
        return s
    parts = _MAKER_SPLIT_RE.split(s)
    out = [_MAKERS.get(p.strip(), p.strip()) for p in parts if p.strip()]
    return ' / '.join(out) if out else s


def format_duty(bureau: Any, runner: Any) -> str:
    """车次担当单位全称：`担当局 + 担当段` 直接拼接（不缩写）。

    RailGo 常见组合：`北京局集团公司` + `北京客运段` →
    `北京局集团公司北京客运段`；也兼容 `南昌局` + `南昌客运段` →
    `南昌局南昌客运段`。若 runner 已自带局名则不重复拼接。
    """
    b = full_bureau(bureau)
    r = full_bureau(runner)
    if not b:
        return r
    if not r:
        return b
    if r.startswith(b) or b in r:
        return r
    return b + r


def format_train_range(start: Any, end: Any) -> str:
    """始发 → 终到（缺一边时只显示已有的一边）。"""
    a, b = _clean(start), _clean(end)
    if a and b:
        return '%s → %s' % (a, b)
    return a or b